#!/usr/bin/env bun
/*
 * Translations: their types, and their exchange with a translation service (POEditor).
 *
 * Every slice (a feature, a page, a layout) keeps its own texts in `_translation/<name>.<language>.yml`.
 *   generate  writes `_translation/index.ts` beside the YAML files of every slice under src/: the texts of all languages and
 *             one type for all of them, taken from the default language's file (features/translation/languages.ts)
 *   collect   merges the slices of each group (GROUPS) into one file per language here, `<group>.<language>.yml`, each slice
 *             under its name, to upload to the service
 *   update    splits the files downloaded from the service, named like the collected ones, back into the slices; a new
 *             language gets new files in every slice
 *
 * Run with Bun: `bun translations/translations.ts <generate | collect | update>` (package.json: `translations:*`)
 */

import { fileURLToPath } from "node:url"
import { dirname, join, relative } from "node:path"
import { readdir, readFile, rm, writeFile } from "node:fs/promises"
import { Document, parse, parseDocument } from "yaml"
import { defaultLanguage, languages, type Language } from "../src/features/translation/languages"

type Data = string | number | boolean | null | Data[] | { [ key:string ]: Data }
type TranslationFile = { path: string, fileName: string, name: string, language: string }

// The slices uploaded together: each group is one file per language. Paths use the tsconfig aliases
const GROUPS:Record<string, string[]> = {
  cactuJam: [ `@/pages/cactu-jam` ],
}

const ALIASES:Record<string, string> = { "@lib/":`src/lib/`, "@fet/":`src/features/`, "@/":`src/` }
const TRANSLATION_DIRECTORY = `_translation`
const TRANSLATION_FILE = /^(?<name>[\w-]+)\.(?<language>[\w-]+)\.ya?ml$/
const FRONTEND = fileURLToPath( new URL( `../`, import.meta.url ) )
const EXCHANGE = fileURLToPath( new URL( `./`, import.meta.url ) )

const commands = { generate, collect, update }
const command = commands[ process.argv[ 2 ] as keyof typeof commands ]

if (!command) {
  console.error( `The first argument should be one of: ${Object.keys( commands ).join( `, ` )}. Passed: "${process.argv[ 2 ] ?? ``}"` )
  process.exit( 1 )
}

await command()

async function generate() {
  const directories = await findTranslationDirectories()

  for (const directory of directories) {
    const files = await readTranslationFiles( directory )
    const where = relative( FRONTEND, directory )

    const source = files.find( file => file.language === defaultLanguage )
    if (!source) throw new Error( `${where}: no ${defaultLanguage} file, the source of the translation's type` )

    const missing = languages.filter( language => !files.some( file => file.language === language ) )
    if (missing.length) console.warn( `${where}: no ${missing.join( `, ` )} texts yet, ${defaultLanguage} is used instead` )

    const unknown = files.filter( file => !languages.includes( file.language as Language ) )
    if (unknown.length) console.warn( `${where}: ${unknown.map( file => file.language ).join( `, ` )} not in features/translation/languages.ts, unused` )

    const typeName = `${source.name.charAt( 0 ).toUpperCase()}${source.name.slice( 1 )}Translation`
    const data = parse( await readFile( source.path, `utf-8` ) ) as Data
    const sortedFiles = files.toSorted( (a, b) => b.fileName.localeCompare( a.fileName ) )
    const entries = sortedFiles.map( file => identifierOf( file.language ) === file.language ? file.language : `"${file.language}":${identifierOf( file.language )}` )

    const content = [
      `// Generated by translations/translations.ts from the YAML files beside it; do not edit`,
      ...sortedFiles.map( file => `import ${identifierOf( file.language )} from "./${file.fileName}"` ),
      `import type { Translation } from "@fet/translation"`,
      ``,
      `export type ${typeName} = ${typeOf( data, `` )}`,
      ``,
      `export default { ${entries.join( `, ` )} } as Translation<${typeName}>`,
      ``,
    ].join( `\n` )

    await writeIfChanged( join( directory, `index.ts` ), content )
  }

  console.log( `Translation types generated: ${directories.length}` )
}

async function collect() {
  // Only the collected files: this folder also holds this script
  for (const fileName of await readdir( EXCHANGE )) {
    if (TRANSLATION_FILE.test( fileName )) await rm( join( EXCHANGE, fileName ) )
  }

  const grouped = new Set<string>()

  for (const [ group, slicePaths ] of Object.entries( GROUPS )) {
    const sectionsByLanguage = new Map<string, string[]>()

    for (const slicePath of slicePaths) {
      const directory = resolveSlice( slicePath )
      grouped.add( directory )

      for (const file of await readTranslationFiles( directory )) {
        const text = await readFile( file.path, `utf-8` )
        const section = `${file.name}:\n${text.trimEnd().split( `\n` ).map( line => `  ${line}`.trimEnd() ).join( `\n` )}\n`
        const sections = sectionsByLanguage.get( file.language ) ?? []

        sectionsByLanguage.set( file.language, [ ...sections, section ] )
      }
    }

    for (const [ language, sections ] of sectionsByLanguage) {
      await writeFile( join( EXCHANGE, `${group}.${language}.yml` ), sections.join( `\n` ), `utf-8` )
      console.log( `Collected: ${group}.${language}.yml` )
    }
  }

  const ungrouped = (await findTranslationDirectories()).filter( directory => !grouped.has( directory ) )
  for (const directory of ungrouped) console.warn( `Not in any group (GROUPS), not collected: ${relative( FRONTEND, directory )}` )
}

async function update() {
  const exchangeFiles = (await readdir( EXCHANGE )).map( fileName => ({ fileName, match:fileName.match( TRANSLATION_FILE ) }) )

  for (const [ group, slicePaths ] of Object.entries( GROUPS )) {
    const groupFiles = exchangeFiles.filter( ({ match }) => match?.groups?.name === group )

    for (const { fileName, match } of groupFiles) {
      const language = match!.groups!.language
      const document = parseDocument( await readFile( join( EXCHANGE, fileName ), `utf-8` ) )

      for (const slicePath of slicePaths) {
        const directory = resolveSlice( slicePath )
        const [ existing ] = await readTranslationFiles( directory )
        if (!existing) continue

        // Comments inside the slice's section stay with it
        const section = document.get( existing.name, true )
        if (!section) continue

        await writeIfChanged( join( directory, `${existing.name}.${language}.yml` ), new Document( section ).toString({ lineWidth:0 }) )
      }

      console.log( `Updated from: ${fileName}` )
    }
  }
}

async function findTranslationDirectories() {
  const paths = await readdir( join( FRONTEND, `src` ), { recursive:true } )
  const yamlPaths = paths.filter( path => TRANSLATION_FILE.test( path.split( /[\\/]/ ).at( -1 )! ) )
  const directories = yamlPaths.map( path => join( FRONTEND, `src`, dirname( path ) ) )

  return [ ...new Set( directories ) ].filter( directory => directory.endsWith( TRANSLATION_DIRECTORY ) )
}

async function readTranslationFiles( directory:string ): Promise<TranslationFile[]> {
  const fileNames = await readdir( directory ).catch( () => [] as string[] )

  return fileNames.flatMap( fileName => {
    const groups = fileName.match( TRANSLATION_FILE )?.groups
    if (!groups) return []

    return [ { path:join( directory, fileName ), fileName, name:groups.name, language:groups.language } ]
  } )
}

function resolveSlice( slicePath:string ) {
  const alias = Object.keys( ALIASES ).find( prefix => slicePath.startsWith( prefix ) )
  const path = alias ? ALIASES[ alias ] + slicePath.slice( alias.length ) : slicePath

  return join( FRONTEND, path, TRANSLATION_DIRECTORY )
}

async function writeIfChanged( path:string, content:string ) {
  const current = await readFile( path, `utf-8` ).catch( () => undefined )
  if (current === content) return

  await writeFile( path, content, `utf-8` )
}

/** `pl` stays `pl`, `pt-BR` becomes `ptBR` */
function identifierOf( language:string ) {
  return language.replace( /-(\w)/g, (_, letter:string) => letter.toUpperCase() )
}

function typeOf( value:Data, indent:string ): string {
  if (value === null) return `null`
  if (Array.isArray( value )) return value.length ? `${typeOf( value[ 0 ], indent )}[]` : `unknown[]`
  if (typeof value !== `object`) return typeof value

  const innerIndent = `${indent}  `
  const members = Object.entries( value ).map( ([ key, member ]) => `${innerIndent}${quoteKey( key )}: ${typeOf( member, innerIndent )}` )

  return `{\n${members.join( `\n` )}\n${indent}}`
}

function quoteKey( key:string ) {
  return /^[A-Za-z_$][\w$]*$/.test( key ) ? key : JSON.stringify( key )
}
